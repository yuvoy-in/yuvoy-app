#!/usr/bin/env node
/**
 * The compact lockup: the ensō and the YUVOY caps, without the tagline.
 *
 * ## Why this is generated and not drawn
 *
 * The delivered horizontal lockup bakes the script tagline and its tapered
 * underline into the same file as the mark, so there was no way to show the
 * logo anywhere without also showing a strapline over the content. That is
 * what yuvoy-app#36 asked to stop, first on the reels feed and then, on
 * 14 Sep, on every page.
 *
 * Hand-editing the file was the other option and is the one this repo already
 * refuses for the delivered lockups: they are generated by yuvoy-web's
 * `generate-header-lockup.mjs` and never touched, because a hand-edit is
 * invisible in review and is silently lost the next time the brand redelivers.
 * So this derives the compact form from the delivered one, and re-running it
 * after a redelivery is the whole maintenance story.
 *
 * The output is now the ONLY wordmark this app draws. The `lockup` variant of
 * `<Wordmark>` and the two delivered files under `public/brand` are both gone,
 * so nothing can reach a screen with a tagline on it.
 *
 * ## What it does
 *
 *   1. Keeps the two ensō paths and the YUVOY caps. Drops the script tagline
 *      and its underline.
 *   2. **Re-centres the caps against the ensō.** In the full lockup the caps
 *      sit above the tagline and the ensō is centred against the pair; remove
 *      the tagline and the caps are left riding the top of a mark twice their
 *      height. This is the only geometry the script invents, and it invents
 *      the one value that keeps the drawing balanced rather than a new
 *      composition.
 *   3. Crops the viewBox to the remaining art with the same ~6px margin the
 *      delivered files carry.
 *
 * ONE recolour, and only on the dark variant (v2.9). The source files carry
 * their own tones and the light one is forest/terra-deep here as there. The
 * dark one is not: yuvoy-web's delivered lockup is drawn in `cream`, which is
 * that site's canvas and no longer this one's, so its light tone is mapped to
 * `--color-paper` on the way through.
 *
 * Without it this script is a loaded gun. It is the thing that runs after a
 * brand redelivery, it writes into `public/brand`, and it would have written
 * a cream mark back over the white one with nothing failing — the drawing is
 * correct, the geometry is correct, and only the colour is a year out of
 * date. The mapping reads BOTH hexes out of the two repos' own @theme blocks
 * rather than naming either, so it cannot drift from either side.
 *
 * Reads from the sibling yuvoy-web checkout, which is where the delivered
 * files live. Writes into this repo's `public/brand`.
 *
 *     node scripts/generate-feed-lockup.mjs
 *     node scripts/generate-feed-lockup.mjs /path/to/brand   # source elsewhere
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** A `--color-<name>` hex out of a repo's @theme block. */
function token(globalsPath, name) {
  const css = readFileSync(globalsPath, "utf8");
  const hex = new RegExp(`--color-${name}:\\s*(#[0-9a-fA-F]{6})`).exec(
    css,
  )?.[1];
  if (!hex) throw new Error(`no --color-${name} in ${globalsPath}`);
  return hex.toLowerCase();
}

const BRAND = join(process.cwd(), "public/brand");
const MARGIN = 6;

/*
  Where the delivered lockup is read from.

  It used to be `public/brand` here, alongside the output. This repo no longer
  keeps a copy: the delivered files were byte-identical duplicates of
  yuvoy-web's, they bake the tagline into the art, and yuvoy-app#36 asked for
  the tagline to be gone from `public` as well as from every screen. Deleting
  them without moving the input would have left this script unable to run
  after a brand redelivery, which is the only reason it exists.

  yuvoy-web is where the delivered lockups are generated
  (`scripts/generate-header-lockup.mjs`), so it is the source, not a second
  copy. Override with an argument when the checkout is somewhere else:

      node scripts/generate-feed-lockup.mjs ../some/other/brand
*/
const SOURCE =
  process.argv[2] ?? join(process.cwd(), "../yuvoy-web/public/brand");

/** Every path in the file, with its own transform, in document order. */
function parsePaths(svg) {
  return [...svg.matchAll(/<path\s+d="([^"]*)"([^/]*)\/>/g)].map((m) => {
    const [, d, attrs] = m;
    const t = /translate\(([-\d.]+)\s+([-\d.]+)\)/.exec(attrs);
    const s = /scale\(([-\d.]+)\)/.exec(attrs);
    return {
      d,
      attrs: attrs.trim(),
      tx: t ? Number(t[1]) : 0,
      ty: t ? Number(t[2]) : 0,
      scale: s ? Number(s[1]) : 1,
    };
  });
}

/**
 * A path's bounding box in its own coordinates.
 *
 * Safe as plain number pairs because the delivered art is fully polygonised —
 * `M`, `L` and `Z` only, verified below. A curve command would make alternate
 * numbers control points rather than vertices and quietly widen every box, so
 * the script refuses rather than guessing.
 */
function bbox(d) {
  const commands = new Set(d.match(/[A-Za-z]/g));
  for (const c of commands) {
    if (!"MLZmlz".includes(c)) {
      throw new Error(
        `path uses "${c}"; this script only understands polygonised M/L/Z art. ` +
          `Re-check the delivered file before trusting the crop.`,
      );
    }
  }
  const n = d.match(/-?\d+\.?\d*/g).map(Number);
  const xs = n.filter((_, i) => i % 2 === 0);
  const ys = n.filter((_, i) => i % 2 === 1);
  return {
    x0: Math.min(...xs),
    x1: Math.max(...xs),
    y0: Math.min(...ys),
    y1: Math.max(...ys),
  };
}

/** The same box, after the path's own translate/scale. */
function worldBox(p, group = { tx: 0, ty: 0, scale: 1 }) {
  const b = bbox(p.d);
  const k = p.scale * group.scale;
  const ox = group.tx + p.tx * group.scale;
  const oy = group.ty + p.ty * group.scale;
  return {
    x0: ox + b.x0 * k,
    x1: ox + b.x1 * k,
    y0: oy + b.y0 * k,
    y1: oy + b.y1 * k,
  };
}

function build(tone) {
  const from = join(SOURCE, `yuvoy-lockup-on-${tone}.svg`);
  let src;
  try {
    src = readFileSync(from, "utf8");
  } catch {
    throw new Error(
      `no delivered lockup at ${from}. The source lives in yuvoy-web, not ` +
        `here (yuvoy-app#36). Pass its brand directory as an argument if the ` +
        `checkout is elsewhere.`,
    );
  }
  const paths = parsePaths(src);
  if (paths.length !== 5) {
    throw new Error(
      `expected 5 paths in the ${tone} lockup and found ${paths.length}. ` +
        `The brand file changed shape; re-read it before regenerating.`,
    );
  }

  const g =
    /<g transform="translate\(([-\d.]+)\s+([-\d.]+)\)\s*scale\(([-\d.]+)\)">/.exec(
      src,
    );
  if (!g) throw new Error(`no ensō group transform in the ${tone} lockup`);
  const group = { tx: Number(g[1]), ty: Number(g[2]), scale: Number(g[3]) };

  // 0,1 = the ensō and its dot, inside the group. 2 = the YUVOY caps.
  // 3 = the script tagline. 4 = its underline. The last two are dropped.
  const [ensoBody, ensoDot, caps] = paths;
  const enso = [ensoBody, ensoDot].map((p) => worldBox(p, group));
  const ensoBox = {
    y0: Math.min(...enso.map((b) => b.y0)),
    y1: Math.max(...enso.map((b) => b.y1)),
    x0: Math.min(...enso.map((b) => b.x0)),
    x1: Math.max(...enso.map((b) => b.x1)),
  };
  const capsBox = worldBox(caps);

  // The one invented number: drop the caps so their centre meets the ensō's.
  const shift = (ensoBox.y0 + ensoBox.y1) / 2 - (capsBox.y0 + capsBox.y1) / 2;
  const capsY = caps.ty + shift;

  const art = {
    x0: Math.min(ensoBox.x0, capsBox.x0),
    x1: Math.max(ensoBox.x1, capsBox.x1),
    y0: Math.min(ensoBox.y0, capsBox.y0 + shift),
    y1: Math.max(ensoBox.y1, capsBox.y1 + shift),
  };
  const view = {
    x: round(art.x0 - MARGIN),
    y: round(art.y0 - MARGIN),
    w: round(art.x1 - art.x0 + MARGIN * 2),
    h: round(art.y1 - art.y0 + MARGIN * 2),
  };

  const out =
    `<svg role="img" aria-labelledby="title desc" xmlns="http://www.w3.org/2000/svg" viewBox="${view.x} ${view.y} ${view.w} ${view.h}">\n` +
    `<title id="title">Yuvoy</title>\n` +
    `<desc id="desc">Yuvoy brush-circle mark beside the YUVOY wordmark.</desc>\n` +
    `<!-- Generated by scripts/generate-feed-lockup.mjs from the delivered ${tone} header lockup in yuvoy-web. Do not hand-edit. -->\n` +
    `<g>\n` +
    `<g transform="translate(${group.tx} ${group.ty}) scale(${group.scale})">\n` +
    `<path d="${ensoBody.d}" ${ensoBody.attrs}/>\n` +
    `<path d="${ensoDot.d}" ${ensoDot.attrs}/>\n` +
    `</g>\n` +
    `<path d="${caps.d}" ${caps.attrs.replace(
      /translate\([-\d.]+\s+[-\d.]+\)/,
      `translate(${caps.tx} ${round(capsY)})`,
    )}/>\n` +
    `</g>\n</svg>\n`;

  const dest = join(BRAND, `yuvoy-mark-compact-on-${tone}.svg`);
  writeFileSync(dest, tone === "dark" ? recolour(out) : out);
  return { tone, view, shift: round(shift), dest };
}

const round = (n) => Math.round(n * 100) / 100;

/*
  The delivered dark lockup's light tone, mapped to this repo's canvas.

  Both ends are read rather than typed: the source's from yuvoy-web's @theme,
  the destination's from ours. If either repo moves its canvas again this
  follows it, and if yuvoy-web ever adopts `paper` too the mapping becomes the
  identity and quietly stops mattering.
*/
function recolour(svg) {
  const from = token(join(SOURCE, "../../src/app/globals.css"), "cream");
  const to = token(join(process.cwd(), "src/app/globals.css"), "paper");
  const swapped = svg.replace(new RegExp(from, "gi"), to);
  if (from !== to && swapped === svg) {
    throw new Error(
      `the delivered dark lockup carries no ${from}; yuvoy-web's canvas token ` +
        `and its brand files have diverged, so the recolour would be silent.`,
    );
  }
  return swapped;
}

for (const tone of ["dark", "light"]) {
  const r = build(tone);
  console.log(
    `✓ ${r.dest.split("/").pop()}  viewBox="${r.view.x} ${r.view.y} ${r.view.w} ${r.view.h}"  caps dropped ${r.shift}`,
  );
}
